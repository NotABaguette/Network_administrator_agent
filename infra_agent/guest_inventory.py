def guests_of(inventory: SeedInventory) -> list[SeedDevice]:
    return sorted(
        (device for device in inventory.devices if device.kind in GUEST_KINDS),
        key=lambda device: device.name,
    )


def ansible_inventory(inventory: SeedInventory) -> dict[str, Any]:
    """The Ansible inventory as data, so it can be asserted without a file.

    Connection settings only: no user, no password, no key path. The playbooks
    are run by a human with `--user` / `--private-key` or a vault, because this
    file is committed and the platform's secrets live in SOPS.
    """
    groups: dict[str, dict[str, Any]] = {
        "guest_linux": {
            "hosts": {},
            "vars": {
                "ansible_connection": "ssh",
                "ansible_python_interpreter": "auto_silent",
                "exporter_port": NODE_EXPORTER_PORT,
            },
        },
        "guest_windows": {
            "hosts": {},
            "vars": {
                "ansible_connection": "winrm",
                "ansible_port": 5986,
                "ansible_winrm_transport": "ntlm",
                "ansible_winrm_scheme": "https",
                "ansible_winrm_server_cert_validation": "ignore",
                "exporter_port": WINDOWS_EXPORTER_PORT,
            },
        },
    }
    for device in guests_of(inventory):
        group = groups[device.kind.value]
        host: dict[str, Any] = {"ansible_host": device.mgmt_ip}
        if device.kind is DeviceKind.guest_linux and device.port:
            host["ansible_port"] = device.port
        if device.tags:
            host["infra_tags"] = list(device.tags)
        group["hosts"][device.name] = host
    return {"all": {"children": groups}}


def prometheus_targets(inventory: SeedInventory) -> list[dict[str, Any]]:
    """file_sd rows for the `guests` scrape job, one target per guest."""
    rows: list[dict[str, Any]] = []
    for device in guests_of(inventory):
        port = EXPORTER_PORTS[device.kind]
        rows.append(
            {
                "targets": [f"{device.mgmt_ip}:{port}"],
                "labels": {
                    "device": device.name,
                    "platform": "guest",
                    "os": "windows" if device.kind is DeviceKind.guest_windows else "linux",
                    "exporter": (
                        "windows_exporter"
                        if device.kind is DeviceKind.guest_windows
                        else "node_exporter"
                    ),
                },
            }
        )
    return rows


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def write_ansible_inventory(inventory: SeedInventory, path: Path | None = None) -> Path:
    target = path or ANSIBLE_INVENTORY
    body = yaml.safe_dump(ansible_inventory(inventory), sort_keys=False, default_flow_style=False)
    return _write(target, GENERATED_HEADER + body)


def write_prometheus_targets(inventory: SeedInventory, path: Path | None = None) -> Path:
    target = path or PROMETHEUS_TARGETS
    # file_sd is JSON, which has no comments: the header lives in a label-free
    # first entry nowhere, so the note goes in the file name and the docs.
    return _write(target, json.dumps(prometheus_targets(inventory), indent=1) + "\n")


def write_all(
    inventory: SeedInventory | None = None,
    settings: Settings | None = None,
    *,
    root: Path | None = None,
) -> list[Path]:
    """Rewrite both generated files; returns what was written."""
    settings = settings or get_settings()
    inventory = inventory if inventory is not None else SeedInventory.load(settings.seed_inventory)
    base = root or Path.cwd()
    return [
        write_ansible_inventory(inventory, base / ANSIBLE_INVENTORY),
        write_prometheus_targets(inventory, base / PROMETHEUS_TARGETS),
    ]
